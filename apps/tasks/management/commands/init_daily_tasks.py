class Command(BaseCommand):
    help = "Инициализирует шаблоны заданий и вопросов"

    def handle(self, *args, **options):
        from apps.tasks.models import TaskTemplate
        from apps.questions.models import QuestionTemplate

        created_tasks = 0
        for title, description, emoji in TASK_TEMPLATES:
            _, created = TaskTemplate.objects.get_or_create(
                title=title,
                defaults={"description": description, "emoji": emoji},
            )
            if created:
                created_tasks += 1

        created_questions = 0
        for text in QUESTION_TEMPLATES:
            _, created = QuestionTemplate.objects.get_or_create(text=text)
            if created:
                created_questions += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Создано {created_tasks} шаблонов заданий и {created_questions} шаблонов вопросов"
            )
        )
